import { useEffect } from 'react'
import Lenis from 'lenis'

// Enables buttery smooth momentum scrolling site-wide.
// Automatically disabled for users who prefer reduced motion.
export function useLenis() {
  useEffect(() => {
    if (typeof window === 'undefined') return
    const prefersReduced = window.matchMedia?.('(prefers-reduced-motion: reduce)').matches
    if (prefersReduced) return

    const lenis = new Lenis({
      duration: 0.1,
      easing: (t) => Math.min(1, 1.001 - Math.pow(2, -10 * t)),
      smoothWheel: true,
      wheelMultiplier: 1,
      touchMultiplier: 1.2,
      lerp: 0.2
    })
    
























































































































































































































































































































































































































































































































































































































    
    let rafId
    const raf = (time) => {
      lenis.raf(time)
      rafId = requestAnimationFrame(raf)
    }
    rafId = requestAnimationFrame(raf)

    // Bridge Lenis with scrollIntoView / hash navigation used by scrollToSection
    const onAnchor = (e) => {
      const target = e.target?.closest?.('[data-lenis-target]')
      if (!target) return
    }
    document.addEventListener('click', onAnchor)

    return () => {
      cancelAnimationFrame(rafId)
      lenis.destroy()
      document.removeEventListener('click', onAnchor)
    }
  }, [])
}
